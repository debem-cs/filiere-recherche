%% KAPITZA PENDULUM: GENERATE AMPLITUDE-FREQUENCY RESULTS
%
% This script runs KP_sim.slx for a grid of base displacement amplitudes
% and excitation frequencies.
%
% Required variables used by KP_sim.slx:
%   A             base displacement amplitude [m]
%   frequencyHz   excitation frequency [Hz]
%   x0            integrator initial condition [theta; thetaDot]
%
% Required model output:
%   x             Timeseries containing [theta, thetaDot]
%
% Give the MATLAB Function block the inputs x, t, A and frequencyHz.
% Constant blocks with values A and frequencyHz can supply the last two.
% The imposed vertical acceleration is
%
%   u(t) = A*(2*pi*frequencyHz)^2*cos(2*pi*frequencyHz*t).
%
% Set the Integrator initial-condition field to x0.
% Set the To Workspace block variable name to x and its format to Timeseries.

clear;
clc;
close all;

%% 1. VALUES CHOSEN BY THE ENGINEER

modelName = 'KP_sim';

% All input and output data are kept in the generated folder beside this
% script.
projectFolder = fileparts(mfilename('fullpath'));
outputFolder = fullfile(projectFolder,'generated');

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

% Stability data previously generated by kapitza_stability_map.m.
stabilityDataFile = fullfile(outputFolder,'kapitza_stability_data.mat');

% Physical simulation grid.
amplitudeValues = linspace(0.25,0.70,23);  % base displacement amplitude [m]
frequencyValues = linspace(1.00,6.00,61); % excitation frequency [Hz]

% Initial positions used to estimate attraction.
% Initial angular velocity is zero in every case.
initialAngleDegrees = 5:10:85;
initialAngularVelocity = 0;              % [rad/s]

% The settling-time figure uses an intermediate nonlinear initial angle.
% Settling times for every angle are still stored in the results file.
referenceSettlingAngleDegrees = 35;

% Keep the DFT referenced to the small-angle simulation.
dftInitialAngleDegrees = 5;

% Simulation duration and output resolution.
% The damping is small, so hundreds of periods are required before a
% stable trajectory reaches a small neighbourhood of the equilibrium.
numberOfSimulationPeriods = 1200;
samplesPerPeriod = 50;

% Settling criterion.
stateAmplitudeToleranceDegrees = 0.5;    % [deg]
numberOfSettledPeriods = 10;

% DFT of the final part of every 5-degree simulation.
numberOfDFTPeriods = 32;

%% 2. PREPARE RESULT MATRICES

numberOfAmplitudes = length(amplitudeValues);
numberOfFrequencies = length(frequencyValues);
numberOfInitialAngles = length(initialAngleDegrees);

referenceSettlingAngleIndex = find( ...
    initialAngleDegrees == referenceSettlingAngleDegrees,1);
dftInitialAngleIndex = find( ...
    initialAngleDegrees == dftInitialAngleDegrees,1);

if isempty(referenceSettlingAngleIndex) || isempty(dftInitialAngleIndex)
    error('The settling and DFT reference angles must belong to initialAngleDegrees.');
end

stateAmplitudeTolerance = deg2rad(stateAmplitudeToleranceDegrees);

% Load the Floquet map that defines the region to be simulated.
if ~isfile(stabilityDataFile)
    error(['Stability data not found: ' stabilityDataFile newline ...
        'Set stabilityDataFile to the correct generated folder.']);
end

stabilityData = load(stabilityDataFile);

stableOnSimulationGrid = false(numberOfAmplitudes,numberOfFrequencies);
log10SpectralRadiusOnSimulationGrid = ...
    NaN(numberOfAmplitudes,numberOfFrequencies);

for amplitudeIndex = 1:numberOfAmplitudes
    for frequencyIndex = 1:numberOfFrequencies

        A = amplitudeValues(amplitudeIndex);
        frequencyHz = frequencyValues(frequencyIndex);
        omega = 2*pi*frequencyHz;

        alpha = -stabilityData.Omega^2/omega^2;
        beta = A/stabilityData.L;

        interpolatedLog10SpectralRadius = interp2( ...
            stabilityData.alphaValues, ...
            stabilityData.betaValues, ...
            stabilityData.log10SpectralRadius, ...
            alpha,beta,'linear',NaN);

        log10SpectralRadiusOnSimulationGrid(amplitudeIndex,frequencyIndex) = ...
            interpolatedLog10SpectralRadius;

        stableOnSimulationGrid(amplitudeIndex,frequencyIndex) = ...
            interpolatedLog10SpectralRadius < 0;
    end
end

numberOfStableGridPoints = sum(stableOnSimulationGrid,'all');
fprintf('%d of %d grid points are inside the Floquet-stable region.\n', ...
    numberOfStableGridPoints,numberOfAmplitudes*numberOfFrequencies);

if numberOfStableGridPoints == 0
    error('No Floquet-stable points were found inside the selected grid.');
end

% One-sided DFT length. It is identical for all grid points because the
% same number of samples per excitation period is used in every run.
numberOfDFTSamples = numberOfDFTPeriods*samplesPerPeriod;
numberOfDFTBins = floor(numberOfDFTSamples/2) + 1;

settlingTimeAllAngles = ...
    NaN(numberOfAmplitudes,numberOfFrequencies,numberOfInitialAngles);
converged = false(numberOfAmplitudes,numberOfFrequencies,numberOfInitialAngles);
attractionAngle = zeros(numberOfAmplitudes,numberOfFrequencies);

dftAmplitude = NaN(numberOfDFTBins,numberOfAmplitudes,numberOfFrequencies);
dftComplex = complex( ...
    NaN(numberOfDFTBins,numberOfAmplitudes,numberOfFrequencies), ...
    NaN(numberOfDFTBins,numberOfAmplitudes,numberOfFrequencies));
dftFrequencyHz = NaN(numberOfDFTBins,numberOfFrequencies);

%% 3. OPEN THE MODEL AND RUN THE GRID

load_system(modelName);
set_param(modelName,'FastRestart','on');

totalGridPoints = numberOfAmplitudes*numberOfFrequencies;
gridPointNumber = 0;

for amplitudeIndex = 1:numberOfAmplitudes

    A = amplitudeValues(amplitudeIndex);

    for frequencyIndex = 1:numberOfFrequencies

        gridPointNumber = gridPointNumber + 1;

        if mod(gridPointNumber,10) == 0 || gridPointNumber == totalGridPoints
            percentComplete = 100*gridPointNumber/totalGridPoints;
            fprintf('%5.1f %% of grid points complete\n',percentComplete);
        end

        % The Floquet map already tells us whether this pair is stable.
        % Do not spend simulation time outside that region.
        if ~stableOnSimulationGrid(amplitudeIndex,frequencyIndex)
            continue;
        end

        frequencyHz = frequencyValues(frequencyIndex);
        omega = 2*pi*frequencyHz;
        excitationPeriod = 1/frequencyHz;
        stopTime = numberOfSimulationPeriods*excitationPeriod;
        maximumTimeStep = excitationPeriod/samplesPerPeriod;
        requiredSettledTime = numberOfSettledPeriods*excitationPeriod;

        for angleIndex = 1:numberOfInitialAngles

            initialAngle = deg2rad(initialAngleDegrees(angleIndex));
            x0 = [initialAngle; initialAngularVelocity];

            simulationInput = Simulink.SimulationInput(modelName);
            simulationInput = simulationInput.setVariable('A',A);
            simulationInput = simulationInput.setVariable('frequencyHz',frequencyHz);
            simulationInput = simulationInput.setVariable('x0',x0);
            simulationInput = simulationInput.setModelParameter( ...
                'StopTime',num2str(stopTime), ...
                'MaxStep',num2str(maximumTimeStep));

            simulationOutput = sim(simulationInput);

            % The To Workspace block must save x as a Timeseries.
            xSignal = simulationOutput.x;
            time = xSignal.Time;
            state = squeeze(xSignal.Data);

            % Put samples in rows and states in columns if necessary.
            if size(state,1) ~= length(time)
                state = state.';
            end

            theta = state(:,1);
            thetaDot = state(:,2);

            % theta = 0 modulo 2*pi is the upright position.
            wrappedTheta = atan2(sin(theta),cos(theta));

            % Equivalent angular amplitude of the state. Dividing the
            % velocity by the excitation frequency gives both terms the
            % same units and does not penalize the fast periodic motion.
            stateAmplitude = sqrt(wrappedTheta.^2 + (thetaDot/omega).^2);
            insideTolerance = stateAmplitude <= stateAmplitudeTolerance;

            % A run is converged when it enters the tolerance region and
            % remains there for at least the requested number of periods.
            lastOutsideSample = find(~insideTolerance,1,'last');

            if isempty(lastOutsideSample)
                candidateSettlingTime = 0;
            elseif lastOutsideSample < length(time)
                candidateSettlingTime = time(lastOutsideSample + 1);
            else
                candidateSettlingTime = NaN;
            end

            if ~isnan(candidateSettlingTime)
                remainingTime = time(end) - candidateSettlingTime;

                if remainingTime >= requiredSettledTime
                    converged(amplitudeIndex,frequencyIndex,angleIndex) = true;
                end
            end

            if converged(amplitudeIndex,frequencyIndex,angleIndex)
                settlingTimeAllAngles(amplitudeIndex,frequencyIndex,angleIndex) = ...
                    candidateSettlingTime;
            end

            % The DFT is stored only for the selected small initial angle.
            if angleIndex == dftInitialAngleIndex

                % Store the final DFT for every Floquet-stable grid point.
                dftStartTime = time(end) - numberOfDFTPeriods*excitationPeriod;
                uniformTime = linspace(dftStartTime,time(end),numberOfDFTSamples + 1).';
                uniformTime(end) = [];

                uniformTheta = interp1(time,theta,uniformTime,'linear');
                uniformTheta = uniformTheta - mean(uniformTheta);

                completeDFT = fft(uniformTheta)/numberOfDFTSamples;
                oneSidedDFT = completeDFT(1:numberOfDFTBins);

                twoSidedAmplitude = abs(completeDFT);
                oneSidedAmplitude = twoSidedAmplitude(1:numberOfDFTBins);
                oneSidedAmplitude(2:end-1) = 2*oneSidedAmplitude(2:end-1);

                sampleFrequency = samplesPerPeriod*frequencyHz;
                frequencyAxis = (0:numberOfDFTBins-1).' ...
                    *sampleFrequency/numberOfDFTSamples;

                dftAmplitude(:,amplitudeIndex,frequencyIndex) = oneSidedAmplitude;
                dftComplex(:,amplitudeIndex,frequencyIndex) = oneSidedDFT;
                dftFrequencyHz(:,frequencyIndex) = frequencyAxis;
            end
        end
    end
end

set_param(modelName,'FastRestart','off');

% Two-dimensional settling-time map selected for plotting.
settlingTime = settlingTimeAllAngles(:,:,referenceSettlingAngleIndex);

%% 4. ESTIMATE THE ATTRACTION ANGLE

% attractionAngle is the largest consecutive tested initial angle that
% converged, starting from 5 degrees. For example, a value of 45 degrees
% means that 5, 15, 25, 35 and 45 degrees converged.

for amplitudeIndex = 1:numberOfAmplitudes
    for frequencyIndex = 1:numberOfFrequencies

        for angleIndex = 1:numberOfInitialAngles

            if converged(amplitudeIndex,frequencyIndex,angleIndex)
                attractionAngle(amplitudeIndex,frequencyIndex) = ...
                    initialAngleDegrees(angleIndex);
            else
                break;
            end
        end
    end
end

%% 5. SAVE THE SIMULATION AND DFT RESULTS

save(fullfile(outputFolder,'KP_grid_results.mat'), ...
    'amplitudeValues', ...
    'frequencyValues', ...
    'initialAngleDegrees', ...
    'referenceSettlingAngleDegrees', ...
    'dftInitialAngleDegrees', ...
    'settlingTime', ...
    'settlingTimeAllAngles', ...
    'converged', ...
    'attractionAngle', ...
    'stableOnSimulationGrid', ...
    'log10SpectralRadiusOnSimulationGrid', ...
    'numberOfSimulationPeriods', ...
    'samplesPerPeriod', ...
    'stateAmplitudeToleranceDegrees', ...
    'numberOfSettledPeriods');

% The spectral data are kept in a separate file because they occupy much
% more memory than the settling-time and attraction maps.
save(fullfile(outputFolder,'KP_DFT_results.mat'), ...
    'amplitudeValues', ...
    'frequencyValues', ...
    'stableOnSimulationGrid', ...
    'dftAmplitude', ...
    'dftComplex', ...
    'dftFrequencyHz', ...
    'dftInitialAngleDegrees', ...
    'numberOfDFTPeriods', ...
    'samplesPerPeriod');
